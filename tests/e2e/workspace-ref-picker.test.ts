import { execFile } from "node:child_process";
import { mkdir, mkdtemp, rm } from "node:fs/promises";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { promisify } from "node:util";
import { _electron as electron, type ElectronApplication } from "playwright";
import { expect, it } from "vitest";
import { createTempGitRepository } from "../fixtures/temp-repo";

const exec = promisify(execFile);

it("manages selected branches and worktrees from anchored pickers without batch switching", async () => {
  const fixture = await createTempGitRepository();
  const appData = await mkdtemp(join(tmpdir(), "gitcrest-ref-picker-"));
  const git = (...args: string[]) => exec("git", ["-C", fixture.path, ...args]);
  let app: ElectronApplication | undefined;
  try {
    await git("branch", "-m", "main");
    await git("commit", "--allow-empty", "-m", "seed");
    for (const branch of ["alpha", "beta", "review", "release"]) await git("branch", branch);
    await git("init", "--bare", join(appData, "remote.git"));
    await git("remote", "add", "origin", join(appData, "remote.git"));
    await git("push", "-u", "origin", "main", "alpha", "beta");
    await git("worktree", "add", join(appData, "review-tree"), "review");
    await git("worktree", "add", join(appData, "release-tree"), "release");
    app = await electron.launch({ args: [".", "--lang=en-US", "--disable-gpu", `--user-data-dir=${join(appData, "profile")}`], env: { ...process.env, ELECTRON_RENDERER_URL: "", GITCREST_DATABASE_PATH: join(appData, "gitcrest.sqlite") } });
    const window = await app.firstWindow();
    await window.waitForLoadState("domcontentloaded");
    await window.evaluate(() => localStorage.setItem("gitcrest-locale", "en"));
    await window.reload();
    await window.setViewportSize({ width: 1440, height: 1000 });
    await window.locator(".connectionBadge.connected").waitFor({ timeout: 40_000 });
    const opened = await window.evaluate(async repositoryPath => {
      const connection = await (window as unknown as { gitcrest: { getSidecarConnection: () => Promise<{ baseUrl: string; token: string }> } }).gitcrest.getSidecarConnection();
      return (await fetch(new URL("/api/v1/repositories", connection.baseUrl), { method: "POST", headers: { Authorization: `Bearer ${connection.token}`, "X-GitCrest-API-Version": "1", "Content-Type": "application/json" }, body: JSON.stringify({ path: repositoryPath }) })).status;
    }, fixture.path);
    expect(opened).toBe(200);
    await window.reload();
    await window.locator(".repositoryRowOpen").click();
    await window.locator(".worktreeSelector").waitFor();
    const branchTrigger = window.locator(".workspaceToolbar .branchSelector:not(.worktreeSelector)");
    await branchTrigger.click();
    const picker = window.locator(".anchoredBranchPicker");
    await picker.waitFor();
    await window.locator(".worktreeSelector").click();
    await picker.waitFor({ state: "hidden" });
    await window.locator(".worktreeSwitcherMenu").waitFor();
    await branchTrigger.click();
    await picker.waitFor();
    await window.locator(".worktreeSwitcherMenu").waitFor({ state: "hidden" });
    const anchor = (await branchTrigger.boundingBox())!;
    const panel = (await picker.boundingBox())!;
    expect(Math.abs(panel.y - anchor.y - anchor.height - 5)).toBeLessThan(2);
    const screenshots = join(tmpdir(), "gitcrest-ref-picker-preview");
    await mkdir(screenshots, { recursive: true });
    await picker.getByRole("checkbox", { name: "Select alpha", exact: true }).waitFor();
    await window.screenshot({ path: join(screenshots, "branches.png") });
    await picker.getByRole("checkbox", { name: "Select alpha", exact: true }).check();
    await picker.getByRole("checkbox", { name: "Select beta", exact: true }).check();
    await picker.getByRole("button", { name: "Pull", exact: true }).click();
    const pull = window.getByRole("dialog", { name: "Pull selected branches · 2", exact: true });
    await pull.getByRole("button", { name: "Confirm and run", exact: true }).click();
    await expect.poll(() => pull.getByText("Succeeded", { exact: true }).count(), { timeout: 15_000 }).toBe(2);
    await pull.locator(".sharedDialogFooter").getByRole("button", { name: "Close", exact: true }).click();
    await picker.getByRole("checkbox", { name: "Select alpha", exact: true }).check();
    await picker.getByRole("checkbox", { name: "Select beta", exact: true }).check();
    await picker.getByRole("button", { name: "alpha", exact: true }).click({ button: "right" });
    const menu = window.getByRole("menu", { name: "Actions for alpha", exact: true });
    expect(await menu.getByRole("menuitem").count()).toBe(4);
    await menu.getByRole("menuitem", { name: "Delete selected branches", exact: true }).click();
    const batch = window.getByRole("dialog", { name: "Delete selected branches · 2", exact: true });
    await batch.getByRole("button", { name: "Confirm and run", exact: true }).click();
    await expect.poll(() => batch.getByText("Succeeded", { exact: true }).count(), { timeout: 15_000, message: "Both reviewed branch deletes should finish successfully" }).toBe(2);
    await batch.locator(".sharedDialogFooter").getByRole("button", { name: "Close", exact: true }).click();
    expect((await git("branch", "--show-current")).stdout.trim()).toBe("main");
    expect((await git("branch", "--list", "alpha", "beta")).stdout.trim()).toBe("");
    await window.keyboard.press("Escape");

    await window.locator(".worktreeSelector").click();
    const worktrees = window.locator(".worktreeSwitcherMenu");
    expect(await worktrees.evaluate(node => node.scrollWidth <= node.clientWidth)).toBe(true);
    expect(await worktrees.evaluate(node => [...node.querySelectorAll(".worktreeSwitcherBranch, .worktreePickerRow > .iconButton")].every(item => item.getBoundingClientRect().right <= node.getBoundingClientRect().right))).toBe(true);
    await worktrees.getByRole("checkbox", { name: "Select review-tree", exact: true }).check();
    await worktrees.getByRole("checkbox", { name: "Select release-tree", exact: true }).check();
    await window.screenshot({ path: join(screenshots, "worktrees.png") });
    await worktrees.getByRole("menuitemradio", { name: /review-tree/ }).click({ button: "right" });
    const worktreeMenu = window.getByRole("menu", { name: /review-tree/ });
    expect(await worktreeMenu.getByRole("menuitem").count()).toBe(2);
    await worktreeMenu.getByRole("menuitem", { name: "Remove selected worktrees", exact: true }).click();
    const removal = window.getByRole("dialog", { name: "Remove selected worktrees · 2", exact: true });
    await removal.getByRole("button", { name: "Confirm and run", exact: true }).click();
    await expect.poll(() => removal.getByText("Succeeded", { exact: true }).count(), { timeout: 15_000 }).toBe(2);
    await removal.locator(".sharedDialogFooter").getByRole("button", { name: "Close", exact: true }).click();
    expect((await git("branch", "--list", "review", "release")).stdout).toContain("review");
    expect((await git("worktree", "list", "--porcelain")).stdout).not.toContain("review-tree");
    expect((await git("branch", "--show-current")).stdout.trim()).toBe("main");
  } finally {
    await app?.close();
    await fixture.cleanup();
    await rm(appData, { recursive: true, force: true, maxRetries: 20, retryDelay: 100 });
  }
}, 90_000);
